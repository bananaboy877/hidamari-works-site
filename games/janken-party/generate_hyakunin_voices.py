INTRO = "百人一首かるた！上の句を聞いて、正しい下の句のボタンを押してください。"


def gen(text, path, force=False):
    if not force and os.path.exists(path):
        return False
    url = f"{VOICEVOX}/audio_query?text={urllib.parse.quote(text)}&speaker={SPEAKER}"
    q = json.loads(urllib.request.urlopen(urllib.request.Request(url, method="POST")).read())
    q["speedScale"] = 0.92
    q["pitchScale"] = 0.0
    q["volumeScale"] = 1.0
    wav = urllib.request.urlopen(urllib.request.Request(
        f"{VOICEVOX}/synthesis?speaker={SPEAKER}",
        data=json.dumps(q).encode(),
        headers={"Content-Type": "application/json"},
        method="POST",
    )).read()
    with open(path, "wb") as f:
        f.write(wav)
    print(f"  OK: {os.path.basename(path)} ({len(wav)//1024} KB) <- {text}")
    return True


def write_data_json():
    """JS が読み込むデータファイルを出力"""
    os.makedirs(DATA_DIR, exist_ok=True)
    data = {
        "speaker_id": SPEAKER,
        "count": len(HYAKUNIN),
        "poems": [
            {"number": i + 1, "author": author, "lines": lines}
            for i, (author, lines) in enumerate(HYAKUNIN)
        ],
    }
    path = os.path.join(DATA_DIR, "hyakunin.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f"  OK: {path} ({len(HYAKUNIN)}首)")


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    write_data_json()
    print(f"\n=== VOICEVOX 百人一首生成 (speaker_id={SPEAKER}) ===")
    print(f"出力先: {OUT_DIR}")
    print(f"対象: {len(HYAKUNIN)}首 × 5行 = {len(HYAKUNIN) * 5}ファイル\n")

    count = 0
    skip = 0
    errors = []
    for i, (author, lines) in enumerate(HYAKUNIN, 1):
        for line_idx, text in enumerate(lines, 1):
            path = os.path.join(OUT_DIR, f"{i:03d}_{line_idx}.wav")
            try:
                if gen(text, path):
                    count += 1
                else:
                    skip += 1
            except Exception as e:
                print(f"  ERROR: {path} -> {e}")
                errors.append(path)

    # イントロ
    intro_path = os.path.join(AUDIO_DIR, "intro_hyakunin.wav")
    try:
        if gen(INTRO, intro_path):
            count += 1
        else:
            skip += 1
    except Exception as e:
        print(f"  ERROR: {intro_path} -> {e}")
        errors.append(intro_path)

    print(f"\n=== 完了: 生成 {count} / スキップ {skip} / 失敗 {len(errors)} ===")
    if errors:
        for e in errors:
            print(f"  - {e}")


if __name__ == "__main__":
    main()
